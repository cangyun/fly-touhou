SCHEMA='continuous-connectome-frozen-cached-game-heldout-evaluation-v1'
PAIR_GAP=.125  # Same original cost-probe unit: one beta8 logit.


def _pad(value):
    return torch.cat((value,value.new_zeros((16-len(value),*value.shape[1:]))),0) if len(value)<16 else value


def _mean(value,mask):return float(np.asarray(value)[mask].mean()) if np.any(mask) else None


def _row_cost_metrics(pred,target):
    pred=np.asarray(pred,np.float64);target=np.asarray(target,np.float64)
    relative_error=np.abs((pred-pred.min(-1,keepdims=True))-(target-target.min(-1,keepdims=True))).mean(-1)
    rank=np.full(len(target),np.nan);pairs_count=np.zeros(len(target),np.int64)
    wins_sum=np.zeros(len(target),np.float64)
    for start in range(0,len(target),1024):
        truth=target[start:start+1024,:,None]-target[start:start+1024,None,:]
        delta=pred[start:start+1024,:,None]-pred[start:start+1024,None,:]
        pairs=truth>PAIR_GAP;counts=pairs.sum((1,2))
        wins=(((delta>0)+.5*(delta==0))*pairs).sum((1,2))
        rank[start:start+len(counts)]=np.divide(wins,counts,out=np.full(len(counts),np.nan),where=counts>0)
        pairs_count[start:start+len(counts)]=counts;wins_sum[start:start+len(counts)]=wins
    chosen=pred.argmin(-1)
    regret=target[np.arange(len(target)),chosen]-target.min(-1)
    return dict(min_centered_MAE=relative_error,scene_rank=rank,pairs=pairs_count,wins=wins_sum,
        regret=regret,best_agreement=regret<=1e-6)


def _cost_summary(rows,mask):
    ranked=mask&np.isfinite(rows['scene_rank']);pairs=int(rows['pairs'][mask].sum())
    return dict(rows=int(mask.sum()),min_centered_MAE=_mean(rows['min_centered_MAE'],mask),
        mean_teacher_cost_regret=_mean(rows['regret'],mask),min_cost_action_agreement=_mean(rows['best_agreement'],mask),
        cost_mixed_scenes=int(ranked.sum()),scene_cost_pair_rank=_mean(rows['scene_rank'],ranked),
        direction_pairs=pairs,pooled_cost_pair_rank=float(rows['wins'][mask].sum()/pairs) if pairs else None)


def _policy_summary(probability,margins,mask):
    movement=probability[:,:18];mass=movement.sum(-1)
    conditional=movement/np.maximum(mass[:,None],1e-30)
    danger=margins<=0;choice=probability.argmax(-1);forced=movement.argmax(-1)
    realmove=mask&(choice<18)
    return dict(rows=int(mask.sum()),danger_probability=_mean((movement*danger).sum(-1),mask),
        conditional_movement_danger_probability=_mean((conditional*danger).sum(-1),mask),
        Bomb_probability=_mean(probability[:,18],mask),greedy_Bomb_count=int((mask&(choice==18)).sum()),
        greedy_movement_rows=int(realmove.sum()),
        greedy19_movement_danger_count=int((realmove&danger[np.arange(len(choice)),choice.clip(0,17)]).sum()),
        forced_movement_greedy_danger_count=int((mask&danger[np.arange(len(choice)),forced]).sum()),
        forced_movement_direction_counts=np.bincount(forced[mask],minlength=18).tolist())


def _trace_contract(rollout):
    shape=tuple(rollout.actions.shape)
    if len(shape)!=2 or shape[1]!=30 or not 1<=shape[0]<=256:raise ValueError('Actual ordered30-world cache rows required')
    for name,tail,dtype in (('encoded_visual',(384,),torch.float32),('features',(25,),torch.float32),
            ('legal_actions',(19,),torch.bool),('actions',(),torch.int64),('game_ids',(),torch.int64),
            ('episode_starts',(),torch.bool),('d95_risk_costs',(18,),torch.float32),
            ('d95_risk_queried_mask',(),torch.bool),('d95_risk_valid_mask',(),torch.bool)):
        value=getattr(rollout,name)
        if (value.shape!=(*shape,*tail) or value.dtype!=dtype or value.device.type!='cpu'
                or value.requires_grad or not bool(torch.isfinite(value).all())):
            raise ValueError('Actual detached source cache field differs:'+name)
    if bool((rollout.d95_risk_valid_mask&~rollout.d95_risk_queried_mask).any()):
        raise ValueError('Postfact-valid costs require actual teacher query')
    for key,tail,dtype in (('margins',(3,18),np.float32),('trusted',(3,),np.bool_),
            ('outcomes',(),np.int8),('unprotected_mask',(),np.bool_)):
        value=np.asarray(getattr(rollout.task_targets,key))
        if value.shape!=(*shape,*tail) or value.dtype!=dtype:raise ValueError('Original compact geometry label differs:'+key)
    return shape


def _population_summary(samples,mask,layout):
    result={}
    for group,name in enumerate(('input_ports','middle_remaining','DN_outputs')):
        ids=layout['input_indices'] if group==0 else layout['output_indices'] if group==2 else samples['middle_indices']
        selected=samples['role_statistics'][mask,group]
        result[name]=dict(neurons=len(ids),sampled_scenes=int(mask.sum()),units='dimensionless ANN activation',
            mean_activation=float(selected[:,0].mean()) if len(selected) else None,
            mean_absolute_activation=float(selected[:,1].mean()) if len(selected) else None,
            mean_within_scene_SD=float(selected[:,2].mean()) if len(selected) else None,
            SD_across_scene_means=float(selected[:,0].std()) if len(selected) else None,
            absolute_activity_gt_095_fraction=float(selected[:,3].mean()) if len(selected) else None,
            absolute_activity_gt_099_fraction=float(selected[:,4].mean()) if len(selected) else None)
    return result


@torch.no_grad()
def evaluate_cached_continuous(model,traces,output,*,max_rows=61440,max_population_scenes=1024,
        annotations_path=DEFAULT_ANNOTATIONS,check_stop=lambda:None,progress=None):
    """Evaluate frozen theta on recorded trajectories from their natural row0.

    `game_id % 5 == 0` is held out globally. Both roles advance their own graph
    activity; the evaluator never trains on either. All inputs must be a
    contiguous rollout-000... chain. There is no late-zero-state mode/resume.
    Population samples use a fixed critical/uniform hash plan shared by initial
    and warmed evaluations, allowing actual same-scene activation comparison.
    """
    if (not isinstance(model,ContinuousConnectomeActorCritic) or type(max_rows) is not int or max_rows<30
            or type(max_population_scenes) is not int or not 1<=max_population_scenes<=2048):
        raise ValueError('Typed continuous model and explicit finite evaluation budgets required')
    if model.core.graph_provenance['require_full_graph'] and model.core.K!=8:
        raise ValueError('This production comparison declares the same continuous K8')
    paths=[Path(p) for p in traces];output=Path(output)
    if not paths or output.exists():raise ValueError('Ordered cache chain and fresh evaluation output required')
    numbers=[]
    for path in paths:
        match=re.fullmatch(r'rollout-(\d+)\.npz',path.name)
        if match is None:raise ValueError('Explicit original rollout filenames required')
        numbers.append(int(match.group(1)))
    if numbers!=list(range(len(paths))) or len({p.resolve().parent for p in paths})!=1:
        raise ValueError('Start at source rollout0 with no skipped/duplicated/mixed-run files')
    begun=time.monotonic();output.mkdir(parents=True)
    paid=dict(data_real_decisions=0,core_batch_calls=0,core_lane_forwards=0,padding_lane_forwards=0,
        population_copy_rows=0,optimizer_updates=0,backward_passes=0,teacher_queries=0,native_actions=0)
    was_training=model.training;model.eval();versions=tuple(p._version for p in model.parameters())
    cpu_rng=torch.get_rng_state().clone()
    try:
        loaded=[];sources=[];candidates=[];offset=0
        for number,path in enumerate(paths):
            check_stop();rollout,source=load_cached_teacher_trace(path);shape=_trace_contract(rollout)
            if offset+shape[0]*30>max_rows:raise ValueError('Actual source rows exceed explicit frozen-evaluation budget')
            loaded.append(rollout);sources.append(source)
            hard=rollout.task_targets.trusted[...,0]&rollout.task_targets.unprotected_mask&\
                (rollout.task_targets.margins[:,:,0]<=0).any(-1)&(rollout.task_targets.margins[:,:,0]>1).any(-1)
            for t in range(shape[0]):
                for w in range(30):
                    gid=int(rollout.game_ids[t,w]);row=offset+t*30+w
                    token=hashlib.sha256(f'continuous-cache-population:{number}:{t}:{w}:{gid}'.encode()).digest()
                    candidates.append((bool(hard[t,w]),token,row))
            offset+=shape[0]*30
        critical_selection=sorted((r for r in candidates if r[0]),key=lambda r:r[1])[:max_population_scenes//2]
        selected_rows={r[2] for r in critical_selection}
        uniform_selection=sorted((r for r in candidates if r[2] not in selected_rows),key=lambda r:r[1])[:max_population_scenes-len(critical_selection)]
        kinds={row:'critical' for critical,token,row in critical_selection}
        kinds.update({row:'uniform_hash' for critical,token,row in uniform_selection})
        layout=_continuous_layout(model.core,annotations_path,not model.core.graph_provenance['require_full_graph'])
        middle=np.setdiff1d(np.arange(model.core.n_neurons),np.union1d(layout['input_indices'],layout['output_indices']))
        state=model.initial_state(30);last_games=None;seen=set();data=[];population=[];counter=0;episode_steps=np.zeros(30,np.int64)
        for file_index,rollout in enumerate(loaded):
            for t in range(len(rollout.actions)):
                check_stop();games=rollout.game_ids[t];starts=rollout.episode_starts[t]
                if last_games is None:
                    if not bool(starts.all()):raise ValueError('Missing actual natural row0:new family cannot inherit old LIF state')
                elif not torch.equal(games!=last_games,starts):raise ValueError('Actual game change and newgame reset marker disagree')
                for game in games[starts].tolist():
                    if game in seen:raise ValueError('A full native game cannot reset twice or appear in two worker lanes')
                    seen.add(game)
                if len(set(games.tolist()))!=30:raise ValueError('Unique actual30 game identities required')
                episode_steps[starts.numpy()]=0
                state=ContinuousConnectomeState(torch.where(starts.to(model.device)[:,None],torch.zeros_like(state.activity),state.activity))
                z=rollout.encoded_visual[t].to(model.device);f=rollout.features[t].to(model.device)
                raw_rows=[];cost_rows=[];next_activity=[]
                for workers in WORKER_GROUPS:
                    check_stop();n=len(workers)
                    raw,_,following=model.forward_encoded(_pad(z[list(workers)]),
                        ContinuousConnectomeState(_pad(state.activity[list(workers)])))
                    DN=model.DN_from_state(following);cost=model.risk_head(DN)
                    raw_rows.append(raw[:n]);cost_rows.append(cost[:n]);next_activity.append(following.activity[:n])
                    paid['core_batch_calls']+=1;paid['core_lane_forwards']+=16;paid['padding_lane_forwards']+=16-n
                    for lane,w in enumerate(workers):
                        global_row=counter+w
                        if global_row not in kinds:continue
                        a=following.activity[lane].detach().cpu().numpy()
                        if not np.isfinite(a).all():raise FloatingPointError('Nonfinite following continuous population')
                        groups=(layout['input_indices'],middle,layout['output_indices'])
                        stats=[]
                        for ids in groups:
                            v=a[ids];stats.append([v.mean(),np.abs(v).mean(),v.std(),(np.abs(v)>.95).mean(),(np.abs(v)>.99).mean()])
                        means=np.bincount(layout['partition'],weights=a,minlength=len(layout['sizes']))/layout['sizes']
                        population.append(dict(row=global_row,game_id=int(games[w]),time=t,world=w,file=file_index,
                            episode_step=int(episode_steps[w]),
                            selection_kind=kinds[global_row],role_statistics=np.asarray(stats,np.float64),population_mean=means.astype(np.float32),
                            input_activation=a[layout['input_indices']].copy(),DN_activation=a[layout['output_indices']].copy(),
                            sampled_cell_activation=a[layout['sampled_indices']].copy()))
                        paid['population_copy_rows']+=1
                state=ContinuousConnectomeState(torch.cat(next_activity));raw=torch.cat(raw_rows);cost=torch.cat(cost_rows)
                combined=model.compose(raw,cost,f);bare=model.policy_logits(raw,f);actual=model.policy_logits(combined,f)
                if not torch.equal(torch.isfinite(actual).cpu(),rollout.legal_actions[t]):raise ValueError('Original actual inventory support differs')
                if not bool(torch.isfinite(raw).all()) or not bool(torch.isfinite(cost).all()):raise FloatingPointError('Nonfinite frozen source predictions')
                data.append(dict(game_id=games.numpy().copy(),features=rollout.features[t].numpy().copy(),
                    source_file=np.full(30,file_index,np.int64),source_time=np.full(30,t,np.int64),world=np.arange(30,dtype=np.int64),
                    cached_episode_step=episode_steps.copy(),
                    raw=raw.cpu().numpy().copy(),predicted_cost=cost.cpu().numpy().copy(),
                    raw_probability=bare.softmax(-1).cpu().numpy().copy(),composed_probability=actual.softmax(-1).cpu().numpy().copy(),
                    target_cost=rollout.d95_risk_costs[t].numpy().copy(),queried=rollout.d95_risk_queried_mask[t].numpy().copy(),
                    cost_valid=rollout.d95_risk_valid_mask[t].numpy().copy(),margins=rollout.task_targets.margins[t].copy(),
                    trusted=rollout.task_targets.trusted[t].copy(),unprotected=rollout.task_targets.unprotected_mask[t].copy(),
                    outcome=rollout.task_targets.outcomes[t].copy()))
                paid['data_real_decisions']+=30;counter+=30;last_games=games.clone();episode_steps+=1
            if progress is not None:progress(dict(schema=SCHEMA,status='replaying',completed_sources=file_index+1,paid=dict(paid),elapsed_seconds=time.monotonic()-begun))
        arrays={key:np.concatenate([r[key] for r in data]) for key in data[0]}
        held=arrays['game_id']%5==0;valid=arrays['queried']&arrays['cost_valid'];train=~held
        prior=arrays['target_cost'][train&valid].mean(0) if (train&valid).any() else None
        predictions=dict(learned_DN_cost=arrays['predicted_cost'])
        if prior is not None:predictions['train_mean_direction_constant']=np.broadcast_to(prior,arrays['target_cost'].shape)
        cost_rows={name:_row_cost_metrics(pred,arrays['target_cost']) for name,pred in predictions.items()}
        normal=normal_unprotected_from_features(torch.from_numpy(arrays['features'])).numpy()
        hard=arrays['trusted'][:,0]&arrays['unprotected']&normal&(arrays['margins'][:,0]<=0).any(-1)&(arrays['margins'][:,0]>1).any(-1)
        policies=dict(raw_actor=arrays['raw_probability'],composed_DN_cost=arrays['composed_probability'])
        raw_tensor=torch.from_numpy(arrays['raw']);f_tensor=torch.from_numpy(arrays['features'])
        # No second graph/head call. Common counterfactual composition on CPU
        # uses the same frozen raw actor and already-recorded teacher costs.
        for name,pred in [('teacher_cost_label_counterfactual',arrays['target_cost'])]+([] if prior is None else [('train_constant_cost',np.broadcast_to(prior,arrays['target_cost'].shape))]):
            cost=torch.from_numpy(np.array(pred,copy=True));combined=model.compose(raw_tensor,cost,f_tensor)
            policies[name]=model.policy_logits(combined,f_tensor).softmax(-1).numpy()
        def scope(mask):
            return dict(rows=int(mask.sum()),games=sorted(set(arrays['game_id'][mask].tolist())),
                queried_cost_rows=int((mask&arrays['queried']).sum()),valid_cost_rows=int((mask&valid).sum()),
                trusted_mixed_geometry_hard_rows=int((mask&hard).sum()),
                cost={name:dict(valid=_cost_summary(row,mask&valid),queried_including_revoked=_cost_summary(row,mask&arrays['queried']),
                    hard_valid=_cost_summary(row,mask&valid&hard)) for name,row in cost_rows.items()},
                hard_policy={name:_policy_summary(p,arrays['margins'][:,0],mask&hard&(arrays['queried'] if name=='teacher_cost_label_counterfactual' else True)) for name,p in policies.items()})
        results=dict(train=scope(train),heldout=scope(held),heldout_per_game={str(g):scope(arrays['game_id']==g) for g in sorted(set(arrays['game_id'][held].tolist()))})
        sample_games=np.array([r['game_id'] for r in population],np.int64)
        samples=dict(role_statistics=np.stack([r['role_statistics'] for r in population]),middle_indices=middle)
        population_report=dict(train=_population_summary(samples,sample_games%5!=0,layout),heldout=_population_summary(samples,sample_games%5==0,layout),
            annotation_populations=layout['groups'],annotation_provenance=layout['provenance'],
            activation_units='dimensionless ANN activity;not Hz/mV/spikes',fixed_hash_sample_limit=max_population_scenes,
            sampled_scenes=len(population),selection_counts={k:sum(r['selection_kind']==k for r in population) for k in ('critical','uniform_hash')},
            pooling_is_not_an_information_sufficiency_or_causality_test=True)
        selected_rows=np.array([r['row'] for r in population],np.int64)
        encoded_all=np.concatenate([r.encoded_visual.numpy().reshape(-1,384) for r in loaded])
        packet={key:np.stack([r[key] for r in population]) for key in ('role_statistics','population_mean','input_activation','DN_activation','sampled_cell_activation')}
        packet.update(row=selected_rows,game_id=sample_games,heldout=sample_games%5==0,
            selection_kind=np.array([r['selection_kind'] for r in population]),
            encoded_visual=encoded_all[selected_rows].copy(),
            **{key:arrays[key][selected_rows].copy() for key in ('features','target_cost','cost_valid','queried','margins','trusted','unprotected',
                'raw_probability','composed_probability','predicted_cost','source_file','source_time','world','cached_episode_step')})
        temporary=output/'predictions-activities.npz.tmp';payload=output/'predictions-activities.npz'
        with temporary.open('wb') as stream:np.savez_compressed(stream,**packet);stream.flush();os.fsync(stream.fileno())
        os.replace(temporary,payload)
        report=dict(schema=SCHEMA,status='completed_frozen_offline_history_evaluation',sources=sources,paid=paid,
            heldout_definition='global game_id %5 ==0;other games train;no labels optimized by this evaluator',
            first_state='genuine newgame row0;zero continuous activity;never old LIF state',
            source_continuity='contiguous same-run rollout indices + per-row game/start markers;raw native ACK not reread',
            neural_width=16,actual_worlds=30,tail_real_lanes=14,core_K=model.core.K,model_configuration=model.configuration(),
            pair_gap=PAIR_GAP,hard_definition='unprotected & trusted4 & any margin<=0 & any margin>1',
            results=results,population=population_report,population_records=[{k:v for k,v in r.items() if k not in ('role_statistics','population_mean','input_activation','DN_activation','sampled_cell_activation')} for r in population],
            sampled_cells=layout['sampled_cells'],elapsed_seconds=time.monotonic()-begun,
            payload_sha256=hashlib.sha256(payload.read_bytes()).hexdigest(),payload_bytes=payload.stat().st_size,
            optimizer_updates=0,teacher_queries=0,native_actions=0,old_neural_state_loaded=False,
            frozen_parameters_unchanged=tuple(p._version for p in model.parameters())==versions,
            CPU_global_RNG_unchanged=torch.equal(cpu_rng,torch.get_rng_state()),
            interpretation='D95 costs and trusted geometry are fallible proxies;only chosen outcomes are native facts;not autonomous play or proof of missing information')
        write_json(output/'report.json',report)
        return report
    except BaseException as error:
        write_json(output/'failure.json',dict(schema=SCHEMA,status='failed_incomplete_offline_evaluation',error=repr(error),paid=paid,elapsed_seconds=time.monotonic()-begun))
        raise
    finally:model.train(was_training)

