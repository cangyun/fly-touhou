"""Frozen, ordered encoded-history evaluation of the new continuous brain.

No optimizer, native game, teacher query, old LIF state or decoder fit exists
here. Explicit caller invocation can use a caller-owned CPU/CUDA model; import
does not load a checkpoint or start a job. Offline trajectories remain the
recorded behavior's history, not a rollout generated by this evaluated policy.
"""
