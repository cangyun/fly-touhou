"""Recompute legacy rewards from complete original-game evaluation traces."""
from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

from fly_touhou.background import BackgroundTouhouEnv  # noqa: E402
from fly_touhou.experiment import file_sha256  # noqa: E402
from fly_touhou.state import Snapshot  # noqa: E402


def audit(path):
    rows, pending, resolved = 0, None, []
    negative_entry = negative_loss = negative_both = 0
    reward_totals = {}
    max_error = 0.
    with gzip.open(path, 'rt', encoding='utf-8') as stream:
        for line in stream:
            item = json.loads(line)
            if item.get('record_type') != 'transition':
                continue
            before, after = Snapshot.from_dict(item['snapshot']), Snapshot.from_dict(item['next_snapshot'])
            reward, hit, components = BackgroundTouhouEnv.reward(before, after, item['elapsed_frames'])
            if after.stage > before.stage > 0:
                reward += 5.
                components['stage_clear'] = 5.
            max_error = max(max_error, abs(float(item['reward']) - reward))
            entry = bool(before.player and after.player and before.player.state != 4 and after.player.state == 4)
            loss = max(0, before.lives - after.lives)
            negative_entry += int(entry and not loss)
            negative_loss += int(loss > 0 and not entry)
            negative_both += int(entry and loss > 0)
            for name, value in components.items():
                reward_totals[name] = reward_totals.get(name, 0.) + value
            if entry:
                if pending is not None:
                    raise ValueError('Overlapping native hit windows require separate investigation')
                pending = {'entry_step': item.get('step', rows), 'entry_frame': before.stage_frame,
                           'lives_before': before.lives, 'bombs_before': before.bombs,
                           'entry_penalty': components['hit'], 'Bomb_requests': 0,
                           'observed_inventory_drops': 0}
            if pending is not None:
                pending['Bomb_requests'] += int(item['action'] >= 18)
                pending['observed_inventory_drops'] += max(0, before.bombs - after.bombs)
                if loss:
                    pending.update(outcome='native_life_decrement', lost_lives=loss,
                        resolution_step=item.get('step', rows), resolution_frame=after.stage_frame,
                        life_decrement_penalty=components['hit'],
                        legacy_penalty_on_two_different_decisions=bool(not entry))
                    resolved.append(pending)
                    pending = None
                elif after.player and after.player.state == 1:
                    pending.update(outcome='returned_to_controllable_without_observed_life_loss',
                                   resolution_step=item.get('step', rows), resolution_frame=after.stage_frame,
                                   life_decrement_penalty=0.,
                                   legacy_penalty_on_two_different_decisions=False)
                    resolved.append(pending)
                    pending = None
            rows += 1
    if max_error > 1e-10:
        raise ValueError('Trace is not generated by the preserved legacy reward contract')
    return {'path': str(path.resolve()), 'sha256': file_sha256(path), 'decisions': rows,
            'legacy_reward_maximum_recomputation_error': max_error,
            'entry_only_penalty_decisions': negative_entry, 'life_loss_only_penalty_decisions': negative_loss,
            'same_decision_entry_and_life_loss': negative_both,
            'same_miss_penalized_at_entry_and_later_life_loss': sum(
                row['legacy_penalty_on_two_different_decisions'] for row in resolved),
            'reward_components_sum': reward_totals, 'resolved_hit_windows': resolved,
            'unresolved_final_hit_window': pending}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--traces', type=Path, nargs='+', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError('Preserve prior reward audits')
    report = {'schema': 'actual-native-legacy-reward-event-audit-v1',
              'game_started': False, 'new_learning': False,
              'script_sha256': file_sha256(__file__), 'traces': [audit(path) for path in args.traces]}
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'traces': [{'decisions': row['decisions'], 'same_miss_double_penalties':
        row['same_miss_penalized_at_entry_and_later_life_loss'], 'hit_penalty_total': row['reward_components_sum']['hit']}
        for row in report['traces']]}, ensure_ascii=False))


if __name__ == '__main__':
    main()
